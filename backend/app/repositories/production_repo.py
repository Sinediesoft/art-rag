WO_NO = re.compile(r"^WO-(\d{4})-(\d{2,3})$")


class RevisionConflict(Exception):
    """寫回時資料版本和求解開始時不同：求解期間有人改了工單等資料。"""

    def __init__(self, revision: str):
        super().__init__(f"production revision 已是 {revision}")
        self.revision = revision


# 帶 Idempotency-Key 的寫入（services/idempotency.py）執行期間的身分。寫入點（開／取消工單、
# 寫入異動、送核准）在「自己的那個交易裡」把冪等記錄標成 applied——業務寫入與冪等標記要嘛一起
# 提交、要嘛一起不存在，行程在兩者之間中斷也不會讓同一個 key 再寫第二次。
_IDEM: ContextVar[dict | None] = ContextVar("artrag_idempotency", default=None)


class IdempotencyLost(Exception):
    """這個 key 的所有權已經不是自己的（久到被別的請求接手，或記錄已被清掉）：業務寫入不提交。"""


@contextmanager
def idem_scope(account_id: str, operation: str, key: str) -> Iterator[None]:
    token = _IDEM.set({"account_id": account_id, "operation": operation, "key": key, "extra": {}})
    try:
        yield
    finally:
        _IDEM.reset(token)


def idem_note(**extra) -> None:
    """替之後的寫入點補充「重送時重建回應」需要的資料（會跟著標記一起存進資料庫）。"""
    ctx = _IDEM.get()
    if ctx is not None:
        ctx["extra"].update(extra)


_ready: set[str] = set()  # 已經建好 schema 的資料庫（每個行程每個 URL 只跑一次 DDL）
_ready_lock = threading.Lock()


def ensure_schema() -> None:
    u = factory_db.url()
    if u in _ready:
        return
    with _ready_lock:
        if u in _ready:
            return
        with factory_db.connection() as conn:
            factory_db.xact_lock(conn, factory_db.PRODUCTION_WRITE)  # 多個行程同時啟動時只建一次
            conn.execute(_SCHEMA)
        _ready.add(u)


def forget_schema() -> None:
    """測試清掉 schema 後呼叫：下次連線重新建表。"""
    _ready.clear()


def _insert(table: str, row: dict) -> tuple[str, tuple]:
    cols = ", ".join(row)
    marks = ", ".join("%s" for _ in row)
    return f"INSERT INTO production.{table} ({cols}) VALUES ({marks})", tuple(row.values())


class ProductionRepo:
    # ------------------------------------------------------------ 連線
    @contextmanager
    def _write(self) -> Iterator[psycopg.Connection]:
        """寫入交易：先拿寫入鎖（同一時間只有一個寫入交易），區塊結束就提交、出例外就回滾。"""
        ensure_schema()
        with factory_db.connection() as conn:
            factory_db.xact_lock(conn, factory_db.PRODUCTION_WRITE)
            yield conn

    def _read(self, sql: str, params: tuple = ()) -> list[dict]:
        ensure_schema()
        with factory_db.connection() as conn:
            return conn.execute(sql, params).fetchall()

    def _bump(self, conn: psycopg.Connection) -> None:
        conn.execute(
            "INSERT INTO production.meta VALUES ('revision', '1') ON CONFLICT (key) DO UPDATE"
            " SET value = (production.meta.value::bigint + 1)::text"
        )

    def _mark_applied(self, conn: psycopg.Connection, ref: str) -> None:
        """在業務寫入的同一個交易裡，把帶 key 的冪等記錄標成 applied（記下單號與重建回應的資料）。
        記錄不是「執行中」（被別人接手、或已被清掉）就丟 IdempotencyLost——呼叫端不提交。"""
        ctx = _IDEM.get()
        if ctx is None:
            return
        marker = json.dumps({**ctx["extra"], "ref": ref}, ensure_ascii=False, default=str)
        cur = conn.execute(
            "UPDATE production.idempotency SET state = 'applied', response = %s"
            " WHERE account_id = %s AND operation = %s AND idem_key = %s AND state = 'running'",
            (marker, ctx["account_id"], ctx["operation"], ctx["key"]),
        )
        if cur.rowcount != 1:
            raise IdempotencyLost(ref)

    @staticmethod
    def now() -> str:
        return datetime.now(UTC).isoformat()

    def revision(self) -> str:
        """資料版本：庫存資料庫用來判斷要不要重建。還沒寫過任何東西時為 '0'。"""
        rows = self._read("SELECT value FROM production.meta WHERE key = 'revision'")
        return rows[0]["value"] if rows else "0"

    # ------------------------------------------------------------ 工單
    def next_wo_no(self, yymm: str, taken: set[str]) -> str:
        """同月份的下一個工單號。

        taken 是知識庫（含 kb_staging）已用掉的單號，避免 make demo-add 撞號。
        """
        used = set(taken) | {
            r["wo_no"] for r in self._read("SELECT wo_no FROM production.work_orders")
        }
        n = max(
            (int(m.group(2)) for w in used if (m := WO_NO.match(w)) and m.group(1) == yymm),
            default=0,
        )
        return f"WO-{yymm}-{n + 1:02d}"

    def create_work_order(self, row: dict, approval: dict | None = None) -> dict:
        """開一張工單。approval（核准開立）有值時，待核准單的狀態更新、冪等標記都在同一個交易裡。"""
        row = {**row, "status": "已開立", "created_at": self.now()}
        with self._write() as conn:
            conn.execute(*_insert("work_orders", row))
            if approval:
                self._approve_in(conn, approval, row["wo_no"])
            self._mark_applied(conn, row["wo_no"])
            self._bump(conn)
        return row

    def _approve_in(self, conn: psycopg.Connection, approval: dict, change_no: str) -> None:
        conn.execute(
            "UPDATE production.approvals SET status = '已核准', decided_by = %s,"
            " decided_label = %s,"
            " decided_at = %s, decision_note = %s, change_no = %s WHERE ap_no = %s",
            (approval["decided_by"], approval["decided_label"], self.now(),
             approval.get("decision_note"), change_no, approval["ap_no"]),
        )  # fmt: skip

    def cancel_work_order(self, wo_no: str, approval: dict | None = None) -> bool:
        with self._write() as conn:
            cur = conn.execute(
                "UPDATE production.work_orders SET status = '已取消'"
                " WHERE wo_no = %s AND status = '已開立'",
                (wo_no,),
            )
            if cur.rowcount:
                if approval:
                    self._approve_in(conn, approval, wo_no)
                self._mark_applied(conn, wo_no)
                self._bump(conn)
            return cur.rowcount > 0

    def get_work_order(self, wo_no: str) -> dict | None:
        rows = self._read("SELECT * FROM production.work_orders WHERE wo_no = %s", (wo_no,))
        return rows[0] if rows else None

    def work_orders(self, include_cancelled: bool = False) -> list[dict]:
        where = "" if include_cancelled else "WHERE status != '已取消'"
        return self._read(f"SELECT * FROM production.work_orders {where} ORDER BY created_at")

    # ------------------------------------------------------------ 排程結果
    def save_run(
        self,
        run: dict,
        ops: list[dict],
        run_id: str | None = None,
        expected_revision: str | None = None,
        fence: Callable[[], None] | None = None,
        audit: dict | None = None,
    ) -> str:
        """寫入一次排程結果（單一交易，持有寫入鎖）。

        expected_revision：求解開始時的資料版本；交易內發現版本變了（有人開／取消工單、改交期…）
        就丟 RevisionConflict、什麼都不寫——舊解不會覆蓋新資料。
        run_id 由呼叫端指定（背景工作用 job_id 推出來的固定值）時是冪等的：同一個 run_id
        已經存在就直接回傳，不重複寫入、不覆蓋（重送、重試、租約過期的舊 worker 延遲寫回）。
        fence：背景工作的資源 fencing，在持有寫入鎖、比對完版本之後、INSERT 之前呼叫；
        丟例外就整個交易回滾（資源租約已被接手的舊 worker 不寫入）。
        audit：和排程結果在同一個交易寫入的稽核紀錄（背景工作用）——排程寫入了就一定有稽核、
        而且只有一筆；不會因為寫入之後的中斷漏記，重送或補做結案也不會重複記。"""
        run_id = run_id or run.get("run_id") or "plan_" + uuid.uuid4().hex[:12]
        row = {
            **run,
            "run_id": run_id,
            "created_at": run.get("created_at") or self.now(),
            "kpis": json.dumps(run.get("kpis") or {}, ensure_ascii=False),
            "analysis": json.dumps(run.get("analysis") or [], ensure_ascii=False),
            "work_orders": json.dumps(run.get("work_orders") or [], ensure_ascii=False),
        }
        with self._write() as conn:
            if expected_revision is not None:
                have = conn.execute(
                    "SELECT value FROM production.meta WHERE key = 'revision'"
                ).fetchone()
                current = have["value"] if have else "0"
                if current != expected_revision:
                    raise RevisionConflict(current)
            if conn.execute(
                "SELECT 1 FROM production.schedule_runs WHERE run_id = %s", (run_id,)
            ).fetchone():
                return run_id
            if fence is not None:
                fence()
            conn.execute(*_insert("schedule_runs", row))
            with conn.cursor() as cur:
                cur.executemany(
                    "INSERT INTO production.schedule_ops (run_id, op_id, wo_no, part_id, op_seq,"
                    " op_name, kind, machine_id, start_min, end_min, setup_min, run_min, start_at,"
                    " end_at, pinned) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
                    [
                        (run_id, o["op_id"], o["wo_no"], o["part_id"], o["op_seq"],
                         o["op_name"], o["kind"], o.get("machine_id"), o["start_min"],
                         o["end_min"], o.get("setup_min", 0), o.get("run_min", 0),
                         o["start_at"], o["end_at"], int(bool(o.get("pinned"))))
                        for o in ops
                    ],
                )  # fmt: skip
            self._bump(conn)
            if audit is not None:
                self._insert_audit(conn, audit)
        return run_id

    def committed_run(self, run_id: str) -> dict | None:
        """這個 run_id 是否已經寫入（背景工作寫回後、結案前中斷時，恢復迴圈依此補做結案）。
        先拿寫入鎖再查：有寫入交易正在進行（已通過 fence、還沒提交）就等它提交或回滾才回答，
        所以回 None 時不會有已經開始的寫入在之後才提交。查不了（資料庫連不上）丟例外——
        呼叫端要當成「不確定」。"""
        with self._write() as conn:
            row = conn.execute(
                "SELECT * FROM production.schedule_runs WHERE run_id = %s", (run_id,)
            ).fetchone()
        return self._decode(dict(row)) if row else None

    def find_run(self, run_id: str) -> dict | None:
        rows = self._read(
            "SELECT run_id, status FROM production.schedule_runs WHERE run_id = %s", (run_id,)
        )
        return rows[0] if rows else None

    @staticmethod
    def _decode(run: dict) -> dict:
        for k in ("kpis", "analysis", "work_orders"):
            run[k] = json.loads(run[k]) if run.get(k) else ([] if k != "kpis" else {})
        return run

    def latest_run(self) -> dict | None:
        """目前排程：最新一次完成（含提前結束）的排程。"""
        rows = self._read(
            "SELECT * FROM production.schedule_runs WHERE status IN ('done', 'stopped')"
            " ORDER BY created_at DESC LIMIT 1"
        )
        return self._decode(rows[0]) if rows else None

    def get_run(self, run_id: str) -> dict | None:
        rows = self._read("SELECT * FROM production.schedule_runs WHERE run_id = %s", (run_id,))
        return self._decode(rows[0]) if rows else None

    def run_ops(self, run_id: str) -> list[dict]:
        return self._read(
            "SELECT * FROM production.schedule_ops WHERE run_id = %s"
            " ORDER BY start_min, machine_id",
            (run_id,),
        )

    def recent_runs(self, limit: int = 10) -> list[dict]:
        rows = self._read(
            "SELECT run_id, created_at, engine, engine_version, status, seconds_limit, solve_ms,"
            " score, hard, medium, soft, initial_score, improvements, n_work_orders,"
            " n_operations, kpis, score_check FROM production.schedule_runs"
            " ORDER BY created_at DESC LIMIT %s",
            (limit,),
        )
        return [{**r, "kpis": json.loads(r["kpis"] or "{}")} for r in rows]

    def snapshot(self) -> dict:
        """給庫存資料庫建庫用：有效的使用者工單＋目前排程的各工序＋已寫入的異動（依序重播）。"""
        run = self.latest_run()
        return {
            "work_orders": self.work_orders(),
            "run": run,
            "ops": self.run_ops(run["run_id"]) if run else [],
            "changes": self.changes(),
        }

    # ------------------------------------------------------------ 修改資料（智慧助理）
    def changes(self, limit: int | None = None) -> list[dict]:
        """已寫入的異動，依寫入順序（庫存資料庫重建時照這個順序重播）。"""
        if limit:
            sql = "SELECT * FROM production.data_changes ORDER BY seq DESC LIMIT %s"
            rows = self._read(sql, (int(limit),))
        else:
            rows = self._read("SELECT * FROM production.data_changes ORDER BY seq")
        return [{**r, "params": json.loads(r["params"])} for r in rows]

    def doc_numbers(self) -> set[str]:
        """已用掉的單號（異動、待核准），產生新單號時避開。"""
        rows = self._read(
            "SELECT change_no AS no FROM production.data_changes"
            " UNION SELECT ap_no FROM production.approvals"
        )
        return {r["no"] for r in rows}

    def add_change(self, row: dict, approval: dict | None = None) -> dict:
        """寫入一筆異動（和待核准單的狀態更新在同一個交易裡）並遞增資料版本。"""
        row = {
            **row,
            "params": json.dumps(row["params"], ensure_ascii=False),
            "created_at": self.now(),
        }
        with self._write() as conn:
            conn.execute(*_insert("data_changes", row))
            if approval:
                self._approve_in(conn, approval, row["change_no"])
            self._mark_applied(conn, row["change_no"])
            self._bump(conn)
        return {**row, "params": json.loads(row["params"])}

    def add_approval(self, row: dict) -> dict:
        row = {
            **row,
            **{k: json.dumps(row[k], ensure_ascii=False) for k in ("params", "reasons", "diff")},
            "status": "待核准",
            "created_at": self.now(),
        }
        with self._write() as conn:
            conn.execute(*_insert("approvals", row))
            self._mark_applied(conn, row["ap_no"])
        return self.get_approval(row["ap_no"])  # type: ignore[return-value]

    @staticmethod
    def _decode_approval(r: dict) -> dict:
        return {**r, **{k: json.loads(r[k]) for k in ("params", "reasons", "diff")}}

    def get_approval(self, ap_no: str) -> dict | None:
        rows = self._read("SELECT * FROM production.approvals WHERE ap_no = %s", (ap_no,))
        return self._decode_approval(rows[0]) if rows else None

    def approvals(self, status: str | None = None, requester_id: str | None = None,
                  limit: int = 50) -> list[dict]:  # fmt: skip
        where, params = [], []
        if status:
            where.append("status = %s")
            params.append(status)
        if requester_id:
            where.append("requester_id = %s")
            params.append(requester_id)
        sql = "SELECT * FROM production.approvals" + (
            f" WHERE {' AND '.join(where)}" if where else ""
        )
        sql += " ORDER BY created_at DESC LIMIT %s"
        return [self._decode_approval(r) for r in self._read(sql, (*params, limit))]

    def decide_approval(
        self,
        ap_no: str,
        status: str,
        by: str,
        label: str,
        note: str | None,
        change_no: str | None = None,
    ) -> bool:
        """退回、失效、核准（異動類的核准走 add_change，和寫入同一個交易）。只改「待核准」的單。"""
        with self._write() as conn:
            cur = conn.execute(
                "UPDATE production.approvals SET status = %s, decided_by = %s, decided_label = %s,"
                " decided_at = %s, decision_note = %s, change_no = %s"
                " WHERE ap_no = %s AND status = '待核准'",
                (status, by, label, self.now(), note, change_no, ap_no),
            )
            return cur.rowcount > 0

    def expire_approvals(self, before_iso: str) -> list[str]:
        rows = self._read(
            "SELECT ap_no FROM production.approvals WHERE status = '待核准' AND created_at < %s",
            (before_iso,),
        )
        for r in rows:
            self.decide_approval(r["ap_no"], "已失效", "system", "系統", "超過 24 小時沒人處理")
        return [r["ap_no"] for r in rows]

    def add_audit(self, row: dict, once: bool = False, audit_id: str | None = None) -> None:
        """once：同一個（動作、操作、單號）已經有紀錄就不再寫——冪等重送、中斷後補做收尾時
        不會重複記稽核（這些單號每個只會被寫入一次）。
        audit_id：伺服器產生、一個事件一個的編號（寫在 detail.audit_id 與 audit_id 欄）；
        已經有同一個編號的紀錄就不再寫——補送同一個事件不重複，
        不同事件（即使單號、request_id 相同）各記一筆。
        request_id 來自呼叫端可指定的 X-Request-ID，只當追蹤欄位，不拿來去重（docs/adr/042）。"""
        with self._write() as conn:
            self._insert_audit(conn, row, once, audit_id)

    def _insert_audit(
        self, conn: psycopg.Connection, row: dict, once: bool = False, audit_id: str | None = None
    ) -> None:
        row = {**row, "at": self.now()}
        if audit_id is not None:
            detail = row.get("detail") if isinstance(row.get("detail"), dict) else {}
            row["detail"] = {**detail, "audit_id": audit_id}
            row["audit_id"] = audit_id
        if isinstance(row.get("detail"), (dict, list)):
            row["detail"] = json.dumps(row["detail"], ensure_ascii=False)
        if audit_id is not None:
            # 同一個事件編號只會有一筆（audit_id 有唯一索引；呼叫端都持有寫入鎖，不會同時寫）
            sql, params = _insert("audit_log", row)
            conn.execute(
                sql + " ON CONFLICT (audit_id) WHERE audit_id IS NOT NULL DO NOTHING", params
            )
        elif once:
            cols = ", ".join(row)
            marks = ", ".join("%s" for _ in row)
            conn.execute(
                f"INSERT INTO production.audit_log ({cols}) SELECT {marks} WHERE NOT EXISTS ("
                " SELECT 1 FROM production.audit_log WHERE action = %s"
                " AND op IS NOT DISTINCT FROM %s AND ref_no IS NOT DISTINCT FROM %s)",
                (*row.values(), row.get("action"), row.get("op"), row.get("ref_no")),
            )
        else:
            conn.execute(*_insert("audit_log", row))

    def audit(self, limit: int = 50) -> list[dict]:
        rows = self._read(
            "SELECT id, at, actor_id, actor_label, action, op, ref_no, summary, detail, request_id"
            " FROM production.audit_log ORDER BY id DESC LIMIT %s",
            (limit,),
        )
        for r in rows:
            if r.get("detail") and r["detail"][:1] in "[{":
                r["detail"] = json.loads(r["detail"])
        return rows

    def reset(self) -> None:
        """展示還原：清掉使用者開立的工單、所有排程結果、智慧助理的異動、待核准單與稽核紀錄。"""
        with self._write() as conn:
            conn.execute(
                "TRUNCATE " + ", ".join(f"production.{t}" for t in TABLES) + " RESTART IDENTITY"
            )
            self._bump(conn)

    # ------------------------------------------------------------ 冪等（Idempotency-Key）
    def idem_begin(self, account_id: str, operation: str, key: str, request_hash: str,
                   stale_s: float = 120) -> tuple[str, dict | None]:  # fmt: skip
        """開始一次帶 key 的寫入。回傳 ("new", None)＝輪到你執行；("replay", 先前的回應)；
        ("conflict", None)＝同一個 key 用在參數不同的請求；("busy", None)＝同一個請求還在執行；
        ("resume", 標記)＝前一個執行者已經提交了業務寫入、卻沒來得及收尾（中斷或收尾出錯）：
        不能再寫一次，由呼叫端依標記補做收尾。
        整段持有寫入鎖：跨行程也只有一個人拿到 "new"／"resume"。"""
        with self._write() as conn:
            row = conn.execute(
                "SELECT * FROM production.idempotency WHERE account_id = %s AND operation = %s"
                " AND idem_key = %s",
                (account_id, operation, key),
            ).fetchone()
            now = datetime.now(UTC)
            if row is not None:
                age = (now - datetime.fromisoformat(row["created_at"])).total_seconds()
                if row["request_hash"] != request_hash:
                    return ("conflict", None)
                if row["state"] == "done":
                    return ("replay", json.loads(row["response"]))
                if age < stale_s:
                    return ("busy", None)
                # 前一個執行者當掉了（沒有 done 也沒有 abort）：接手
                conn.execute(
                    "UPDATE production.idempotency SET created_at = %s WHERE account_id = %s"
                    " AND operation = %s AND idem_key = %s",
                    (now.isoformat(), account_id, operation, key),
                )
                # running＝業務寫入還沒提交，重新執行；applied＝已提交，只補收尾
                if row["state"] == "applied":
                    return ("resume", json.loads(row["response"]))
                return ("new", None)
            conn.execute(
                "INSERT INTO production.idempotency VALUES (%s, %s, %s, %s, 'running', NULL, %s)",
                (account_id, operation, key, request_hash, now.isoformat()),
            )
            return ("new", None)

    def idem_finish(self, account_id: str, operation: str, key: str, response: dict) -> None:
        with self._write() as conn:
            conn.execute(
                "UPDATE production.idempotency SET state = 'done', response = %s"
                " WHERE account_id = %s AND operation = %s AND idem_key = %s",
                (json.dumps(response, ensure_ascii=False), account_id, operation, key),
            )

    def idem_abort(self, account_id: str, operation: str, key: str) -> None:
        """執行失敗：業務寫入還沒提交（running）就放掉 key，讓使用者修正後可以用同一個 key 再送；
        已經提交（applied）的不能放掉——只是把它標成「現在沒有人在處理」，下一次重送立刻從標記
        補做收尾，不用等逾時。"""
        with self._write() as conn:
            conn.execute(
                "DELETE FROM production.idempotency WHERE account_id = %s AND operation = %s"
                " AND idem_key = %s AND state = 'running'",
                (account_id, operation, key),
            )
            conn.execute(
                "UPDATE production.idempotency SET created_at = '1970-01-01T00:00:00+00:00'"
                " WHERE account_id = %s AND operation = %s AND idem_key = %s"
                " AND state = 'applied'",
                (account_id, operation, key),
            )

    def ping(self) -> bool:
        try:
            return bool(self._read("SELECT 1 AS ok"))
        except (psycopg.Error, factory_db.FactoryUnavailable):
            return False


